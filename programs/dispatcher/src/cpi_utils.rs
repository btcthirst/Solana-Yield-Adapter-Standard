/// Precomputed Anchor instruction discriminators: sha256("global:<name>")[0..8]
pub fn adapter_discriminator(name: &str) -> [u8; 8] {
    match name {
        "deposit"             => [0xf2, 0x23, 0xc6, 0x89, 0x52, 0xe1, 0xf2, 0xb6],
        "withdraw"            => [0xb7, 0x12, 0x46, 0x9c, 0x94, 0x6d, 0xa1, 0x22],
        "current_value"       => [0xe8, 0xc7, 0xa7, 0xce, 0xf7, 0x38, 0xea, 0x14],
        "initialize_position" => [0xdb, 0xc0, 0xea, 0x47, 0xbe, 0xbf, 0x66, 0x50],
        _ => panic!("unknown adapter instruction: {name}"),
    }
}
